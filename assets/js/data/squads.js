FL.data.rosaDi = function (teamId) { return FL.data.squads[teamId] || []; };
FL.data.rosaPerReparto = function (teamId, ruolo) {
  return FL.data.rosaDi(teamId).filter(function (g) { return g.ruolo === ruolo; });
};
FL.data.ruoliDisponibili = function (teamId) {
  return FL.data.rosaDi(teamId).some(function (g) { return !!g.ruolo; });
};
FL.data.creditiSpesi = function (teamId) {
  return FL.data.rosaDi(teamId).reduce(function (s, g) { return s + (g.costo || 0); }, 0);
};
FL.data.giocatoriTesserati = function () {
  return FL.data.teams.reduce(function (n, t) { return n + FL.data.rosaDi(t.id).length; }, 0);
};
FL.data.giocatorePiuCaro = function (teamId) {
  return FL.data.rosaDi(teamId).slice().sort(function (a, b) { return (b.costo || 0) - (a.costo || 0); })[0] || null;
};
